"""DART 수치 대조 — 실제로 틀렸던 문장은 잡고, 분기 전망·이익률 우연 일치는 통과시킨다.

WHY 2026-10-12 (#187): 공개 글 8편의 10배·100배 단위 오기. DART 값은 실제 응답을 옮겨 둔다.
"""
from __future__ import annotations

import pytest

from korea_finance_factcheck import units as dfc

# 실제 DART fnlttSinglAcnt 2025 값(원). 별도·연결·전기를 섞어 둔다.
_DART = {
    "018670": [("매출액", 4_056_497_791_478), ("매출액", 7_676_318_981_997), ("영업이익", 261_772_090_098)],
    "096770": [("매출액", 4_850_904_693_000), ("매출액", 80_296_054_243_000), ("영업이익", 2_730_034_540_000)],
    "323410": [("매출액", 3_086_291_000_000), ("매출액", 2_945_621_000_000)],
    "052690": [("매출액", 518_767_621_092), ("영업이익", 33_877_678_060)],
    "051900": [("매출액", 6_500_000_000_000), ("영업이익", 170_700_000_000)],
    "005930": [("매출액", 237_900_000_000_000), ("매출액", 333_605_938_000_000), ("영업이익", 23_603_619_000_000)],
}


def _fetch(code):
    return _DART.get(code, [])


@pytest.mark.parametrize("html, code", [
    ("<p>SK가스(018670)는 2025년 매출 405조 6,497억 원, 영업이익 26조 1,772억 원을 기록했다.</p>", "018670"),  # 12619
    ("<p>SK이노베이션(096770)은 2025년 연결 매출 485조 원, 영업이익 273조 원을 공시했다.</p>", "096770"),   # 9571
    ("<p>카카오뱅크(323410). 2025년 카카오뱅크의 매출액은 3,086억 원으로 집계되었다.</p>", "323410"),          # 4047 (10배 작게)
    ("<p>한전기술(052690)</p><p>2025년 한전기술의 매출액은 518,767억 원으로 줄었다.</p>", "052690"),           # 4790 (문단 넘어 회사)
    ("<p>한전기술(052690)의 2025년 매출액은 5조1,876억 원이다.</p>", "052690"),                                  # 4827
])
def test_실제_단위_오기_문장은_잡아야_한다(html, code):
    errs = dfc.find_unit_errors(html, fetch=_fetch)["errors"]
    assert errs and errs[0]["code"] == code


@pytest.mark.parametrize("html", [
    "<p>SK가스(018670)는 2025년 별도 기준 매출 4조 565억 원, 영업이익 2,618억 원을 기록했다.</p>",
    "<p>삼성전자(005930)는 2025년 연결 매출 333조 6,059억 원을 기록했다.</p>",
    # 분기 전망치 — 연간 값과 원래 다르다(10874)
    "<p>LS증권은 LG생활건강(051900)의 2분기 매출을 1조6,574억원, 영업이익을 1,028억원으로 제시했다.</p>",
    # 매출의 1/10 이 영업이익 — 계정이 다르면 비교하지 않는다(7600·4405)
    "<p>LG생활건강(051900)의 영업이익은 6,500억 원 수준으로 본다.</p>",
    # 소수점 금액을 문장 경계로 자르지 않는다
    "<p>삼성전자(005930)의 2분기 연결 매출 2.6조 원은 전망치다.</p>",
    "<p>코스피는 6,625.93에 마감했다.</p>",
])
def test_정상_문장은_통과해야_한다(html):
    assert dfc.find_unit_errors(html, fetch=_fetch)["errors"] == []


def test_조억_표기를_원으로_바꿔야_한다():
    assert dfc.to_won("4조 565억") == pytest.approx(4.0565e12)
    assert dfc.to_won("518,767억") == pytest.approx(5.18767e13)
    assert dfc.to_won("2.6조") == pytest.approx(2.6e12)
    assert dfc.to_won("") is None


def test_DART_조회가_실패하면_생략하고_사유를_남겨야_한다():
    def boom(code):
        raise RuntimeError("timeout")
    res = dfc.find_unit_errors("<p>SK가스(018670) 매출 405조 원.</p>", fetch=boom)
    assert res["errors"] == [] and "실패" in res["skipped"]


def test_DART_값이_없으면_생략으로_표시해야_한다():
    res = dfc.find_unit_errors("<p>SK가스(018670) 매출 405조 원.</p>", fetch=lambda c: [])
    assert res == {"errors": [], "skipped": "DART 값 없음(키 미설정·조회 실패)"}


def test_종목코드가_없으면_조회하지_않아야_한다():
    called = []
    dfc.find_unit_errors("<p>국내 ETF 시장은 500조원 시대다.</p>", fetch=lambda c: called.append(c) or [])
    assert called == []


